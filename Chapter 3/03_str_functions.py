name = "shubham"

print(len(name)) # 'len' length of string
print(name.endswith("ham")) # Giving end letters
print(name.startswith("shu")) # Giving start letters
print(name.capitalize()) # Capitalize first character of string
print(name.lower()) # Convert all characters in a string to lowercase
print(name.upper()) # Convert all characters in a string to uppercase
print(name.title()) # capitalize first charecter of each word in the string
print(name.swapcase()) # Swap the case of all characters in the string